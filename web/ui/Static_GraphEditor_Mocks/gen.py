"""Writes catalog.js from the graph editor's server samples, so the mock shows real nodes."""
import json
from pathlib import Path

here = Path(__file__).parent
samples = here.parent.parent / "graph-editor" / "src" / "graph" / "server-samples"
catalog = json.loads((samples / "nodes.json").read_text(encoding="utf-8"))["nodes"]
graph = json.loads((samples / "builtin.video.json").read_text(encoding="utf-8"))["graph"]
payload = json.dumps({"nodes": catalog, "graph": graph}, indent=1)
(here / "catalog.js").write_text(
    f"// Generated by gen.py from web/graph-editor server samples. Do not edit.\nwindow.AURORA_MOCK = {payload};\n",
    encoding="utf-8",
)
print(f"catalog.js: {len(catalog)} node types, {len(graph['nodes'])} graph nodes")
