"""Regenerate web/demo/builtin-graphs.js from the server samples of the built-in graphs.

The room runs these two documents on the WASM engine. Re-run after a built-in graph
change (once server-samples is refreshed), from the repo root:

  python web/demo/gen-builtin-graphs.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SAMPLES = os.path.join(ROOT, 'web/graph-editor/src/graph/server-samples')
OUT = os.path.join(ROOT, 'web/demo/builtin-graphs.js')


def graph(name):
    with open(os.path.join(SAMPLES, f'builtin.{name}.json'), encoding='utf-8') as f:
        return json.load(f)['graph']


body = json.dumps({'video': graph('video'), 'audio': graph('audio')}, indent=2)
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by gen-builtin-graphs.py from the built-in graph server samples. Do not edit.\n')
    f.write(f'export const BUILTIN_GRAPHS = {body};\n')
